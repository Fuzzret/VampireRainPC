#!/usr/bin/env python3
"""Regenerates src/stubs.cpp: a logged stub for every kernel/XAM import the
generated code declares (__imp__<Name> in ppc_recomp_shared.h) that has no
GUEST_IMPORT(<Name>) implementation under src/.

Run after implementing more functions:
    python tools/gen_stubs.py ../recomp_out/ppc_recomp_shared.h
"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent.parent
shared = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else here.parent / "recomp_out" / "ppc_recomp_shared.h")

declared = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", shared.read_text())))
implemented = set()
for f in (here / "src").glob("*.cpp"):
    if f.name == "stubs.cpp":
        continue
    implemented |= set(re.findall(r"GUEST_IMPORT\((\w+)\)", f.read_text()))

missing = [n for n in declared if n not in implemented]
extra = sorted(implemented - set(declared))
if extra:
    print("warning: implemented but not imported by the game:", ", ".join(extra))

lines = [
    "// GENERATED by tools/gen_stubs.py - do not edit by hand.",
    "// Kernel/XAM imports without an implementation yet. Each logs its first",
    "// calls (with r3-r6) and returns 0. To implement one, add",
    "// GUEST_IMPORT(Name) { ... } in another source file and re-run the script.",
    '#include "kernel.h"',
    "",
    "namespace",
    "{",
    "    void StubCalled(const char* name, std::atomic<uint32_t>& count, PPCContext& ctx)",
    "    {",
    "        uint32_t n = ++count;",
    "        if (n <= 10 || (n & (n - 1)) == 0)",
    '            LOG("[stub] %s(%08X, %08X, %08X, %08X) call #%u", name, ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, n);',
    "    }",
    "}",
    "",
    "#define STUB(name) \\",
    "    GUEST_IMPORT(name) \\",
    "    { \\",
    "        static std::atomic<uint32_t> count{0}; \\",
    "        StubCalled(#name, count, ctx); \\",
    "        RETURN(0); \\",
    "    }",
    "",
]
lines += [f"STUB({n})" for n in missing]
(here / "src" / "stubs.cpp").write_text("\n".join(lines) + "\n")
print(f"{len(declared)} imports: {len(declared) - len(missing)} implemented, {len(missing)} stubbed")
